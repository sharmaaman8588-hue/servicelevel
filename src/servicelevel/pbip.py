_ALIASES = {"Interval": "i", "Queue": "q", "Calendar": "c", "TimeOfDay": "t"}
_SL = ["SL1 %", "SL2 %", "SL3 %", "SL4 %"]


def _field(table: str, prop: str, measure: bool) -> dict:
    kind = "Measure" if measure else "Column"
    return {
        kind: {"Expression": {"SourceRef": {"Source": _ALIASES[table]}}, "Property": prop},
        "Name": f"{table}.{prop}",
    }


def _visual(
    name: str,
    visual_type: str,
    box: tuple[int, int, int, int],
    roles: dict[str, list[tuple[str, str, bool]]],
    title: str,
    objects: dict | None = None,
) -> dict:
    x, y, w, h = box
    selects, projections, used = [], {}, []
    for role, fields in roles.items():
        projections[role] = []
        for table, prop, is_measure in fields:
            selects.append(_field(table, prop, is_measure))
            projections[role].append({"queryRef": f"{table}.{prop}"})
            if table not in used:
                used.append(table)
    single = {
        "visualType": visual_type,
        "projections": projections,
        "prototypeQuery": {
            "Version": 2,
            "From": [{"Name": _ALIASES[t], "Entity": t, "Type": 0} for t in used],
            "Select": selects,
        },
        "vcObjects": {
            "title": [
                {
                    "properties": {
                        "show": {"expr": {"Literal": {"Value": "true"}}},
                        "text": {"expr": {"Literal": {"Value": f"'{title}'"}}},
                    }
                }
            ]
        },
        "drillFilterOtherVisuals": True,
    }
    if objects:
        single["objects"] = objects
    config = {
        "name": name,
        "layouts": [{"id": 0, "position": {"x": x, "y": y, "z": 0, "width": w, "height": h}}],
        "singleVisual": single,
    }
    return {
        "config": json.dumps(config, separators=(",", ":")),
        "filters": "[]",
        "height": h,
        "width": w,
        "x": x,
        "y": y,
        "z": 0,
    }


def _single_queue_slicer(queue: str) -> dict:
    """Single-select slicer that opens on one queue, so one queue's shortage is not netted."""
    literal = {"Literal": {"Value": f"'{queue}'"}}
    column = {"Column": {"Expression": {"SourceRef": {"Source": "q"}}, "Property": "queue"}}
    return {
        "general": [
            {
                "properties": {
                    "filter": {
                        "filter": {
                            "Version": 2,
                            "From": [{"Name": "q", "Entity": "Queue", "Type": 0}],
                            "Where": [
                                {
                                    "Condition": {
                                        "In": {"Expressions": [column], "Values": [[literal]]}
                                    }
                                }
                            ],
                        }
                    }
                }
            }
        ],
        "selection": [{"properties": {"singleSelect": {"expr": {"Literal": {"Value": "true"}}}}}],
    }


def _gap_heat_objects() -> dict:
    """Diverging background on the Staffing Gap measure: red short, white balanced, blue spare."""

    def stop(value: int, color: str) -> dict:
        return {
            "color": {"Literal": {"Value": f"'{color}'"}},
            "value": {"Literal": {"Value": f"{value}D"}},
        }

    return {
        "values": [
            {
                "properties": {
                    "backColor": {
                        "solid": {
                            "color": {
                                "expr": {
                                    "FillRule": {
                                        "Input": {
                                            "Measure": {
                                                "Expression": {"SourceRef": {"Source": "i"}},
                                                "Property": "Staffing Gap",
                                            }
                                        },
                                        "FillRule": {
                                            "linearGradient3": {
                                                "min": stop(-3, "#2B6CB0"),
                                                "mid": stop(0, "#FFFFFF"),
                                                "max": stop(3, "#C53030"),
                                                "nullColoringStrategy": {
                                                    "strategy": {"Literal": {"Value": "'asZero'"}}
                                                },
                                            }
                                        },
                                    }
                                }
                            }
                        }
                    }
                },
                "selector": {"metadata": "Interval.Staffing Gap"},
            }
        ]
    }


