def _tag(*parts: str) -> str:
    return str(uuid.uuid5(_NAMESPACE, "/".join(parts)))


@dataclass(frozen=True)
class Column:
    name: str
    data_type: str  # TMDL dataType: string | int64 | double | dateTime
    m_type: str
    format_string: str = ""
    sort_by: str = ""
    tag: str = ""


def _col(name: str, kind: str, sort_by: str = "") -> Column:
    kinds = {
        "text": ("string", "type text", ""),
        "int": ("int64", "Int64.Type", ""),
        "num": ("double", "type number", ""),
        "pct": ("double", "type number", "0.0%"),
        "date": ("dateTime", "type date", "yyyy-mm-dd"),
        "datetime": ("dateTime", "type datetime", "yyyy-mm-dd hh:nn"),
    }
    data_type, m_type, fmt = kinds[kind]
    return Column(name, data_type, m_type, fmt, sort_by, _tag("column", name))


