# (name, from table.column, to table.column): many-to-one from the fact to each dimension.
RELATIONSHIPS = [
    ("Interval_Queue", "Interval.queue", "Queue.queue"),
    ("Interval_Calendar", "Interval.date", "Calendar.date"),
    ("Interval_TimeOfDay", "Interval.interval_idx", "TimeOfDay.interval_idx"),
]


def _quote(name: str) -> str:
    return f"'{name}'" if any(not (ch.isalnum() or ch == "_") for ch in name) else name


@dataclass
class _MeasureView:
    quoted_name: str
    dax: str
    format_string: str
    tag: str
    description: str


@dataclass
class _TableView:
    name: str
    tag: str
    columns: list[Column]
    measures: list[_MeasureView] = field(default_factory=list)


def _env() -> jinja2.Environment:
    text = resources.files("servicelevel").joinpath("templates/table.tmdl.j2").read_text("utf-8")
    env = jinja2.Environment(
        loader=jinja2.DictLoader({"table.tmdl.j2": text}),
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
        undefined=jinja2.StrictUndefined,
    )
    return env


def render_tables() -> dict[str, str]:
    env = _env()
    template = env.get_template("table.tmdl.j2")
    out = {}
    for name, columns in TABLE_COLUMNS.items():
        view = _TableView(name, _tag("table", name), columns)
        if name == registry.FACT_TABLE:
            view.measures = [
                _MeasureView(
                    _quote(m.measure),
                    m.dax,
                    m.format_string,
                    _tag("measure", m.measure),
                    m.description,
                )
                for m in registry.METRICS
            ]
        out[f"definition/tables/{name}.tmdl"] = template.render(table=view)
    return out


def render_model_files(data_folder: str = DEFAULT_DATA_FOLDER) -> dict[str, str]:
    files = {
        "definition.pbism": json.dumps({"version": "4.0", "settings": {}}, indent=2) + "\n",
        "definition/database.tmdl": "database\n\tcompatibilityLevel: 1600\n",
        "definition/model.tmdl": (
            "model Model\n"
            "\tculture: en-US\n"
            "\tdefaultPowerBIDataSourceVersion: powerBI_V3\n"
            "\tdiscourageImplicitMeasures\n"
            "\tsourceQueryCulture: en-US\n\n"
            + "".join(f"ref table {name}\n" for name in TABLE_COLUMNS)
            + "\nref expression DataFolder\n"
        ),
        "definition/expressions.tmdl": (
            f'expression DataFolder = "{data_folder}" meta '
            '[IsParameterQuery=true, Type="Text", IsParameterQueryRequired=true]\n'
            f"\tlineageTag: {_tag('expression', 'DataFolder')}\n"
        ),
        "definition/relationships.tmdl": "\n".join(
            f"relationship {name}\n\tfromColumn: {src}\n\ttoColumn: {dst}\n"
            for name, src, dst in RELATIONSHIPS
        ),
    }
    files.update(render_tables())
    return files


