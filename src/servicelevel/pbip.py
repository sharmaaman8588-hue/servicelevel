def render_project(data_folder: str = DEFAULT_DATA_FOLDER) -> dict[str, str]:
    """Relative path (from the PBIP directory) -> file text, for the whole project."""
    files = {
        f"{PROJECT}.pbip": json.dumps(
            {
                "version": "1.0",
                "artifacts": [{"report": {"path": f"{PROJECT}.Report"}}],
                "settings": {"enableAutoRecovery": True},
            },
            indent=2,
        )
        + "\n"
    }
    for rel, text in render_model_files(data_folder).items():
        files[f"{PROJECT}.SemanticModel/{rel}"] = text
    for rel, text in render_report().items():
        files[f"{PROJECT}.Report/{rel}"] = text
    return files


def write_project(out_dir: Path, data_folder: str = DEFAULT_DATA_FOLDER) -> list[Path]:
    written = []
    for rel, text in render_project(data_folder).items():
        path = out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written
