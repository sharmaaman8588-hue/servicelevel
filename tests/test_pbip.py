def test_tmdl_parser_reads_quoted_measures_and_partitions():
    text = (
        "table Demo\n\tlineageTag: x\n\n"
        "\tmeasure 'A %' = DIVIDE(SUM(Demo[a]), SUM(Demo[b]))\n\t\tformatString: 0.0%\n\n"
        "\tcolumn a\n\t\tdataType: int64\n\t\tsourceColumn: a_src\n\n"
        '\tpartition Demo = m\n\t\tsource =\n\t\t\t\tFile.Contents(DataFolder & "\\Demo.csv")\n'
    )
    t = parse_tmdl_table(text)
    assert t.measures["A %"]["expression"] == "DIVIDE(SUM(Demo[a]), SUM(Demo[b]))"
    assert t.measures["A %"]["formatString"] == "0.0%"
    assert t.columns["a"]["sourceColumn"] == "a_src"
    assert t.csv_name == "Demo.csv"


