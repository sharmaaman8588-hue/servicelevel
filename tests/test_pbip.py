def test_committed_csvs_are_structurally_sound_and_recover_the_planted_patterns():
    """Structural checks, not byte equality: regenerated bytes can differ across numpy/pandas
    releases. Regenerate with `servicelevel generate && servicelevel build`."""
    total = sum((COMMITTED_DATA / n).stat().st_size for n in mart.MART_FILES)
    assert total < 1_000_000
    interval = pd.read_csv(COMMITTED_DATA / "Interval.csv")
    assert list(interval.columns) == mart.INTERVAL_EXPORT_COLUMNS
    assert len(interval) == 8064
    assert (interval.groupby("queue").size() == 56 * 48).all()
    assert (interval.offered == interval.answered + interval.abandoned).all()
    assert (interval.answered_within_t <= interval.answered).all()
    assert (interval.abandoned_within_t <= interval.abandoned).all()
    assert (interval.staffing_gap == interval.required_agents - interval.logged_in).all()
    assert len(pd.read_csv(COMMITTED_DATA / "Calendar.csv")) == 56
    assert len(pd.read_csv(COMMITTED_DATA / "TimeOfDay.csv")) == 48

    con = mart.open_from_dir(COMMITTED_DATA)
    agg = con.execute("SELECT * FROM agg_queue").df().set_index("queue")
    assert agg.loc["billing", "sl1_interval_mean"] - agg.loc["billing", "sl1_pct"] >= 0.08
    assert agg.loc["technical", "sl4_pct"] - agg.loc["technical", "sl1_pct"] >= 0.08
    sales = agg.loc["sales", ["sl1_pct", "sl2_pct", "sl3_pct", "sl4_pct"]]
    assert sales.max() - sales.min() <= 0.03
    assert agg.loc["sales", "abandon_pct"] <= 0.02
    assert agg.is_consistent.all()


