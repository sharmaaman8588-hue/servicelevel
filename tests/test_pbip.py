def _edit_interval(root: Path, old: str, new: str) -> None:
    path = root.parent / "ServiceLevel.SemanticModel/definition/tables/Interval.tmdl"
    text = path.read_text()
    assert old in text
    path.write_text(text.replace(old, new, 1))


